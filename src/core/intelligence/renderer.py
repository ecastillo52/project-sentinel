# ==========================================================
# Historical Intelligence
# ==========================================================

def print_intelligence(statements: list[str]) -> None:
    """
    Render historical intelligence statements.
    """

    if not statements:
        return

    print("Historical Intelligence")
    print()

    for statement in statements:

        wrapped = fill(
            statement,
            width=REPORT_WIDTH - 4,
            initial_indent="• ",
            subsequent_indent="  ",
        )

        print(wrapped)

    blank()

# ==========================================================
# Recommendations
# ==========================================================


def print_recommendations(recommendations: list[dict]) -> None:
    """
    Render Sentinel recommendations.
    """

    heading("Recommendations")

    if not recommendations:

        print("No recommendations.")
        blank()
        return

    for recommendation in recommendations:

        level = recommendation.get("level", "")
        title = recommendation.get("title", "")
        message = recommendation.get("message", "")

        icon = ICONS.get(level, "•")

        print(f"{icon} {title}")
        print()

        wrapped = fill(
            message,
            width=REPORT_WIDTH - 4,
            initial_indent="    ",
            subsequent_indent="    ",
        )

        print(wrapped)
        print()

    blank()


# ==========================================================
# Helpers
# ==========================================================

def heading(title: str) -> None:
    """
    Print a section heading.
    """

    divider()
    print(title)
    divider()
    blank()


def field(label: str, value) -> None:
    """
    Print an aligned label/value pair.
    """

    if value is None:
        value = "--"

    print(f"{label:<{LABEL_WIDTH}} {value}")


def divider() -> None:
    """
    Print divider.
    """

    print(LINE)


def blank() -> None:
    """
    Print blank line.
    """

    print()